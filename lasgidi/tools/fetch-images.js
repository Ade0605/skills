#!/usr/bin/env node
// Downloads the AI-generated illustrations listed in img/manifest.json and
// converts them to 640x400 WebP (needs ImageMagick `convert` or Python Pillow).
// Then run `node tools/fetch-images.js --index` to regenerate src/images.js.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const root = path.join(__dirname, '..'), man = JSON.parse(fs.readFileSync(path.join(root, 'img/manifest.json'), 'utf8'));
function index() {
  const have = man.images.filter(m => fs.existsSync(path.join(root, m.file)));
  const map = {}; have.forEach(m => { map[m.key] = m.file; });
  fs.writeFileSync(path.join(root, 'src/images.js'), '/* Generated by tools/fetch-images.js: pictures that exist in img/. */\n(function (root) { root.LASGIDI_IMAGES = ' + JSON.stringify(map, null, 1) + '; })(typeof globalThis !== \'undefined\' ? globalThis : this);\n');
  console.log('indexed', have.length, 'of', man.images.length);
}
if (process.argv.includes('--index')) { index(); process.exit(0); }
let ok = 0, fail = 0;
for (const m of man.images) {
  const out = path.join(root, m.file), tmp = out + '.png';
  if (fs.existsSync(out)) { ok++; continue; }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  try {
    cp.execFileSync('curl', ['-sSfL', '-o', tmp, m.src], { stdio: 'inherit' });
    try { cp.execFileSync('convert', [tmp, '-resize', '640x400^', '-gravity', 'center', '-extent', '640x400', '-quality', '72', out]); }
    catch (e) { cp.execFileSync('python3', ['-c', 'import sys;from PIL import Image,ImageOps;im=Image.open(sys.argv[1]).convert("RGB");ImageOps.fit(im,(640,400)).save(sys.argv[2],"WEBP",quality=72)', tmp, out]); }
    fs.unlinkSync(tmp); ok++;
  } catch (e) { fail++; console.error('failed', m.key, e.message); }
}
console.log('done', ok, 'failed', fail);
index();
